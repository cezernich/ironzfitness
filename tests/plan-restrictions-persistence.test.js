'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {setup}=require('./empty-plan-regression.test');
const P=require('../js/plan-restrictions');
const source=Array.from({length:70},(_,i)=>({id:'synthetic-'+i,date:P.add('2027-01-04',i),discipline:i%4===0?'strength':'run',duration:60,load:'hard',intervals:[{zone:5}],exercises:['synthetic lift']}));
const block={type:'medical',startDate:'2027-01-11',endDate:'2027-01-17',clearance:'pending'};
const watchdog=setTimeout(()=>{console.error('FAIL: restriction persistence did not finish');process.exit(1);},10000);
(async()=>{
 const h=setup();h.store.set('trainingPlan',JSON.stringify(source));h.store.set('workoutSchedule','[]');
 await h.DB.savePlanRestrictions([block]);
 assert.ok(h.read('trainingPlan').every(e=>e.date<block.startDate));
 assert.equal(h.remote.get('trainingPlan'),h.store.get('trainingPlan'));
 await h.DB.savePlanRestrictions([{...block,clearance:'full'}]);
 const resumed=h.read('trainingPlan');assert.ok(resumed.some(e=>e.date>block.endDate));
 assert.ok(resumed.filter(e=>e._restrictionApplied).every(e=>e.discipline==='run'&&!e.exercises&&!e.intervals),'rebuild never fabricates strength endurance');
 const first=JSON.stringify(resumed);await h.DB.savePlanRestrictions([{...block,clearance:'full'}]);assert.equal(JSON.stringify(h.read('trainingPlan')),first,'editing status does not repeatedly halve workouts');
 const changed=h.read('trainingPlan');const edit=changed.find(e=>e.date>block.endDate);const deleted=changed.find(e=>e.date>edit.date);edit.description='Synthetic athlete edit';h.store.set('trainingPlan',JSON.stringify(changed.filter(e=>e.id!==deleted.id)));
 await h.DB.savePlanRestrictions([]);
 assert.equal(h.read('trainingPlan').find(e=>e.id===edit.id).description,'Synthetic athlete edit','manual future edit survives');
 assert.ok(!h.read('trainingPlan').some(e=>e.id===deleted.id),'deleted future workout not resurrected');
 const before=[...h.store];h.reject();await assert.rejects(h.DB.savePlanRestrictions([block]));assert.deepEqual([...h.store],before,'failed save preserves all state');
 await assert.rejects(h.DB.savePlanRestrictions([{...block,endDate:'bad'}]));assert.deepEqual([...h.store],before);
 const w=setup();w.ob._state.blockedPeriods=[{...block,startDate:'2026-11-09',endDate:'2026-11-15'}];await w.ob._confirmAndSavePlan();
 assert.equal(w.ob._state.currentScreen,'bp-v2-done','intentional pending plan may be saved as paused');
 assert.ok(w.read('trainingPlan').every(e=>e.date<'2026-11-09'));
 assert.match(w.node('bp-v2-done-copy').textContent,/paused/);
 assert.equal(w.remote.get('blockedPeriods'),w.store.get('blockedPeriods'));
 const n=setup();n.ob._state.raceEvents=[];n.ob._state.blockedPeriods=w.ob._state.blockedPeriods;await n.ob._confirmAndSavePlan();
 assert.equal(n.ob._state.currentScreen,'bp-v2-done');assert.ok(n.read('workoutSchedule').every(e=>e.date<'2026-11-09'));
 const html=fs.readFileSync(require('node:path').join(__dirname,'../index.html'),'utf8');for(const id of ['bp-v2-done-copy','bp-v2-done-title'])assert.ok(html.includes('id="'+id+'"'),'real DOM contains '+id);
 clearTimeout(watchdog);console.log('PASS: actual wizard/DB pause, explicit return, repeated edit, manual edits/deletion, atomic failure and real DOM copy');
})().catch(e=>{clearTimeout(watchdog);console.error(e);process.exitCode=1;});
